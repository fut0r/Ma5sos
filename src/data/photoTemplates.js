/*
 * The photographed templates the client chose, under the names the client
 * gave them (except "ليالي باريس", which came without one). Each carries a
 * sample invitation written for its occasion, and where that text sits on the
 * picture:
 *
 *   text.top     how far down the text starts, as a share of the height
 *   text.x       the centre of the text, measured from the left edge
 *   text.width   how wide the text may run
 *   text.panel   true where the picture is too busy for bare text: the text
 *                then sits on a frosted card
 *   tone         'dark' text on a light part of the picture, or 'light'
 *   ink, accent  text colour, and the colour of the confirm button
 *   onAccent     text colour on that button
 *   nameSize     optional: a smaller name, where a long one would push the
 *                text down into a busy part of the picture
 *   fonts        the name's typeface (display) and the rest of the text's,
 *                chosen to suit each picture; see FONTS in PhotoInvite.jsx
 *
 * The earlier, drawn templates (templates.js) stay as they are: they are the
 * ones whose background the customer can change.
 */

